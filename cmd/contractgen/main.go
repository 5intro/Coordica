// contractgen emits public JSON schema and TypeScript types from domain records.
package main

import (
	"coordica/internal/domain"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"time"
)

func main() {
	leaderOnly := flag.Bool("leader-only", false, "generate only the embedded native Leader output contract")
	nativeOnly := flag.Bool("native-only", false, "generate only embedded native output contracts")
	flag.Parse()
	must(os.WriteFile("cmd/coordica/leader.schema.json", leaderSchema(), 0644))
	if *leaderOnly {
		return
	}
	must(os.WriteFile("internal/runner/execution.schema.json", executionSchema(), 0644))
	if *nativeOnly {
		return
	}
	types := []any{domain.ExecutionIntent{}, domain.RunScopeRequest{}, domain.ScopeAssessment{}, domain.AutomationSettings{}, domain.AutomationRequest{}, domain.PlanningDocument{}, domain.GoalContext{}, domain.PlanningSaveRequest{}, domain.LeaderMessage{}, domain.PlanningMessageRequest{}, domain.TaskProposal{}, domain.ScopeProposal{}, domain.MajorDecisionProposal{}, domain.LeaderResult{}, domain.PlanningRun{}, domain.ProposalTaskMapping{}, domain.Decision{}, domain.DecisionResolveRequest{}, domain.ToolScheduling{}, domain.NodeConfigureRequest{}, domain.BlockItem{}, domain.ConnectionInfo{}, domain.CenterEntry{}, domain.LocalInfo{}, domain.Check{}, domain.Project{}, domain.Requirement{}, domain.RequirementProposal{}, domain.NodeSnapshot{}, domain.Task{}, domain.Capability{}, domain.Node{}, domain.Run{}, domain.Review{}, domain.CheckResult{}, domain.Candidate{}, domain.Event{}, domain.Snapshot{}, domain.VersionRequest{}, domain.ScopeRequest{}, domain.RegisterRequest{}, domain.RegisterResponse{}, domain.ClaimRequest{}, domain.Assignment{}, domain.HeartbeatRequest{}, domain.HeartbeatResponse{}, domain.CompleteRequest{}, domain.Problem{}, domain.StopConfirmation{}, domain.BudgetRequest{}, domain.Artifact{}}
	defs := map[string]any{}
	var ts strings.Builder
	ts.WriteString("// Code generated by go run ./cmd/contractgen. DO NOT EDIT.\n")
	for _, v := range types {
		t := reflect.TypeOf(v)
		properties := map[string]any{}
		required := []string{}
		fmt.Fprintf(&ts, "export interface %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			parts := strings.Split(f.Tag.Get("json"), ",")
			if parts[0] == "-" {
				continue
			}
			optional := len(parts) > 1 && parts[1] == "omitempty"
			suffix := ""
			if optional {
				suffix = "?"
			} else {
				required = append(required, parts[0])
			}
			fieldType := tsType(f.Type)
			properties[parts[0]] = schemaType(f.Type)
			if t == reflect.TypeOf(domain.ExecutionIntent{}) {
				properties[parts[0]] = schemaTypeMode(f.Type, true)
				if f.Type.Kind() == reflect.Slice {
					fieldType = "(" + tsType(f.Type.Elem()) + ")[]"
				}
				if parts[0] == "version" {
					fieldType = fmt.Sprint(domain.ExecutionIntentVersion)
				}
				if parts[0] == "status" {
					fieldType = `"completed" | "scope_requested" | "blocked"`
				}
			}
			fmt.Fprintf(&ts, "  %s%s: %s;\n", parts[0], suffix, fieldType)
		}
		ts.WriteString("}\n")
		if t == reflect.TypeOf(domain.ExecutionIntent{}) {
			properties["version"].(map[string]any)["enum"] = []int{domain.ExecutionIntentVersion}
			properties["status"].(map[string]any)["enum"] = []string{"completed", "scope_requested", "blocked"}
		}
		defs[t.Name()] = map[string]any{"type": "object", "properties": properties, "required": required, "additionalProperties": false}
	}
	schema := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": "https://coordica.local/contracts/v1", "title": "Coordica v1", "$defs": defs}
	b, e := json.MarshalIndent(schema, "", "  ")
	must(e)
	must(os.MkdirAll("api", 0755))
	must(os.MkdirAll("web/src", 0755))
	must(os.WriteFile(filepath.Join("api", "v1.schema.json"), append(b, '\n'), 0644))
	must(os.WriteFile("web/src/api.generated.ts", []byte(ts.String()), 0644))
}

var timeType = reflect.TypeOf(time.Time{})

func tsType(t reflect.Type) string {
	if t == timeType {
		return "string"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return tsType(t.Elem()) + " | null"
	case reflect.Slice:
		return "(" + tsType(t.Elem()) + ")[] | null"
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64:
		return "number"
	case reflect.Struct:
		return t.Name()
	}
	panic(t.String())
}
func schemaType(t reflect.Type) any {
	return schemaTypeMode(t, false)
}

func schemaTypeMode(t reflect.Type, nonNullArrays bool) any {
	if t == timeType {
		return map[string]any{"type": "string", "format": "date-time"}
	}
	switch t.Kind() {
	case reflect.Pointer:
		return map[string]any{"anyOf": []any{schemaType(t.Elem()), map[string]any{"type": "null"}}}
	case reflect.Slice:
		var kind any = []string{"array", "null"}
		if nonNullArrays {
			kind = "array"
		}
		return map[string]any{"type": kind, "items": schemaTypeMode(t.Elem(), nonNullArrays)}
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int64:
		return map[string]any{"type": "integer"}
	case reflect.Struct:
		return map[string]any{"$ref": "#/$defs/" + t.Name()}
	}
	panic(t.String())
}

// The native final-output contract is a strict subset of the domain contracts.
// It has no transport records, nullable arrays, or independent proposal DTOs.
func leaderSchema() []byte {
	defs := map[string]any{}
	for _, value := range []any{domain.LeaderResult{}, domain.TaskProposal{}, domain.ScopeProposal{}, domain.MajorDecisionProposal{}} {
		t := reflect.TypeOf(value)
		properties := map[string]any{}
		required := []string{}
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			name := strings.Split(f.Tag.Get("json"), ",")[0]
			properties[name] = schemaTypeMode(f.Type, true)
			required = append(required, name)
		}
		defs[t.Name()] = map[string]any{"type": "object", "properties": properties, "required": required, "additionalProperties": false}
	}
	root := defs["LeaderResult"].(map[string]any)
	// Keep an explicit object root for native structured-output providers.
	schema := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": defs}
	for key, value := range root {
		schema[key] = value
	}
	b, err := json.MarshalIndent(schema, "", "  ")
	must(err)
	return append(b, '\n')
}
func executionSchema() []byte {
	t := reflect.TypeOf(domain.ExecutionIntent{})
	properties := map[string]any{}
	required := []string{}
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		name := strings.Split(f.Tag.Get("json"), ",")[0]
		properties[name] = schemaTypeMode(f.Type, true)
		required = append(required, name)
	}
	properties["version"].(map[string]any)["enum"] = []int{domain.ExecutionIntentVersion}
	properties["status"].(map[string]any)["enum"] = []string{"completed", "scope_requested", "blocked"}
	schema := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": "https://coordica.local/contracts/execution/v1", "title": "Coordica execution intent v1", "type": "object", "properties": properties, "required": required, "additionalProperties": false}
	b, err := json.MarshalIndent(schema, "", "  ")
	must(err)
	return append(b, '\n')
}

func must(e error) {
	if e != nil {
		panic(e)
	}
}
