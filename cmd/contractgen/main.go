func main() {
	leaderOnly := flag.Bool("leader-only", false, "generate only the embedded native Leader output contract")
	nativeOnly := flag.Bool("native-only", false, "generate only embedded native output contracts")
	flag.Parse()
	must(os.WriteFile("cmd/coordica/initialization.schema.json", initializationSchema(), 0644))
	must(os.WriteFile("cmd/coordica/leader.schema.json", leaderSchema(), 0644))
	must(os.WriteFile("cmd/coordica/consult.schema.json", consultSchema(), 0644))
	must(os.WriteFile("cmd/coordica/requirement-change.schema.json", requirementSchema(), 0644))
	if *leaderOnly {
		return
	}
	must(os.WriteFile("internal/runner/execution.schema.json", executionSchema(), 0644))
	if *nativeOnly {
		return
	}
	types := []any{domain.InitializationOperation{}, domain.UserServiceStatus{}, domain.HostLifecycleStatus{}, domain.CenterHealth{}, domain.CenterIdentity{}, domain.CenterRuntimeStatus{}, domain.ProjectPolicyRequest{}, domain.Baseline{}, domain.AnalysisEvidence{}, domain.InitializationQuestion{}, domain.InitializationResult{}, domain.InitializationFeedback{}, domain.Initialization{}, domain.InitializationRequest{}, domain.InitializationAnswer{}, domain.InitializationConfirm{}, domain.ChatSource{}, domain.ChatCredentialRequest{}, domain.ChatCredentialInfo{}, domain.ChatCredentialGrant{}, domain.ConversationInput{}, domain.ChatRequirementInput{}, domain.ConsultResult{}, domain.ConversationRequest{}, domain.ConsultationAccount{}, domain.ChatOverview{}, domain.ChatListQuery{}, domain.ChatItemQuery{}, domain.ChatRequestQuery{}, domain.ChatCancelRequest{}, domain.ChatAgentCapability{}, domain.ChatRun{}, domain.ChatItem{}, domain.ChatPage{}, domain.ChatDetail{}, domain.ExecutionIntent{}, domain.RunScopeRequest{}, domain.ScopeAssessment{}, domain.AutomationSettings{}, domain.AutomationRequest{}, domain.PlanningDocument{}, domain.GoalContext{}, domain.PlanningSaveRequest{}, domain.LeaderMessage{}, domain.PlanningMessageRequest{}, domain.TaskProposal{}, domain.ScopeProposal{}, domain.MajorDecisionProposal{}, domain.LeaderResult{}, domain.PlanningRun{}, domain.ProposalTaskMapping{}, domain.Decision{}, domain.DecisionResolveRequest{}, domain.ModelOption{}, domain.ToolScheduling{}, domain.NodeConfigureRequest{}, domain.BlockItem{}, domain.ConnectionInfo{}, domain.CenterEntry{}, domain.LocalInfo{}, domain.Check{}, domain.Project{}, domain.Requirement{}, domain.RequirementProposal{}, domain.NodeSnapshot{}, domain.Task{}, domain.Capability{}, domain.Node{}, domain.Run{}, domain.Review{}, domain.CheckResult{}, domain.Candidate{}, domain.Event{}, domain.Snapshot{}, domain.VersionRequest{}, domain.ScopeRequest{}, domain.RegisterRequest{}, domain.RegisterResponse{}, domain.ClaimRequest{}, domain.Assignment{}, domain.HeartbeatRequest{}, domain.HeartbeatResponse{}, domain.CompleteRequest{}, domain.Problem{}, domain.StopConfirmation{}, domain.BudgetRequest{}, domain.Artifact{}}
	defs := map[string]any{}
	types = append(types, domain.TestSuite{}, domain.TestSuiteSave{}, domain.VerificationSpec{}, domain.VerificationRequest{}, domain.TestReport{}, domain.CheckPlan{}, domain.TestReadiness{}, domain.RequirementLinkRequest{})
	types = append(types, domain.RequirementEdit{}, domain.RequirementRevision{}, domain.RequirementImpact{}, domain.RequirementChange{}, domain.RequirementDetail{}, domain.RequirementTaskUpdate{}, domain.RequirementNewTask{}, domain.RequirementPlan{})
	var ts strings.Builder
	fmt.Fprintf(&ts, "export const SOURCE_VERSION = %q;\n", domain.SourceVersion)
	ts.WriteString("// Code generated by go run ./cmd/contractgen. DO NOT EDIT.\n")
	fmt.Fprintf(&ts, "export const MAX_RUN_DURATION_SECONDS = %d;\nexport const MAX_TASK_BUDGET_SECONDS = %d;\n", domain.MaxRunDurationSeconds, domain.MaxTaskBudgetSeconds)
	for _, v := range types {
		t := reflect.TypeOf(v)
		properties := map[string]any{}
		required := []string{}
		fmt.Fprintf(&ts, "export interface %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			parts := strings.Split(f.Tag.Get("json"), ",")
			if parts[0] == "-" {
				continue
			}
			optional := len(parts) > 1 && parts[1] == "omitempty" || t == reflect.TypeOf(domain.Project{}) && parts[0] == "total_budget_seconds"
			suffix := ""
			if optional {
				suffix = "?"
			} else {
				required = append(required, parts[0])
			}
			fieldType := tsType(f.Type)
			properties[parts[0]] = schemaType(f.Type)
			if t == reflect.TypeOf(domain.ExecutionIntent{}) {
				properties[parts[0]] = schemaTypeMode(f.Type, true)
				if f.Type.Kind() == reflect.Slice {
					fieldType = "(" + tsType(f.Type.Elem()) + ")[]"
				}
				if parts[0] == "version" {
					fieldType = fmt.Sprint(domain.ExecutionIntentVersion)
				}
				if parts[0] == "status" {
					fieldType = `"completed" | "scope_requested" | "blocked"`
				}
			}
			if t == reflect.TypeOf(domain.Project{}) && parts[0] == "total_budget_seconds" || (t == reflect.TypeOf(domain.ChatOverview{}) || t == reflect.TypeOf(domain.ConsultationAccount{})) && parts[0] == "budget_seconds" {
				ts.WriteString("  /** @deprecated Ignored legacy allowance field; spending is telemetry. */\n")
			}
			fmt.Fprintf(&ts, "  %s%s: %s;\n", parts[0], suffix, fieldType)
		}
		ts.WriteString("}\n")
		if t == reflect.TypeOf(domain.ExecutionIntent{}) {
			properties["version"].(map[string]any)["enum"] = []int{domain.ExecutionIntentVersion}
			properties["status"].(map[string]any)["enum"] = []string{"completed", "scope_requested", "blocked"}
		}
		if t == reflect.TypeOf(domain.ChatListQuery{}) || t == reflect.TypeOf(domain.ChatItemQuery{}) {
			properties["kind"].(map[string]any)["enum"] = []string{"requirements", "tasks", "blocks", "agents", "runs", "consultations", "proposals"}
			if t == reflect.TypeOf(domain.ChatListQuery{}) {
				properties["limit"].(map[string]any)["minimum"] = 1
				properties["limit"].(map[string]any)["maximum"] = 20
				properties["cursor"].(map[string]any)["maxLength"] = 128
			}
		}
		if t == reflect.TypeOf(domain.AutomationSettings{}) {
			properties["planning_timeout_seconds"].(map[string]any)["minimum"] = 1
			properties["planning_timeout_seconds"].(map[string]any)["maximum"] = domain.MaxRunDurationSeconds
			properties["planning_budget_seconds"].(map[string]any)["minimum"] = 1
			properties["planning_budget_seconds"].(map[string]any)["maximum"] = domain.MaxTaskBudgetSeconds
			properties["planning_budget_seconds"].(map[string]any)["description"] = "Finite goal planning cumulative limit; must be >= planning_timeout_seconds. Not a consultation lifetime cap."
			properties["planning_max_retries"].(map[string]any)["minimum"] = 0
			properties["planning_max_retries"].(map[string]any)["maximum"] = 2
		}
		if t == reflect.TypeOf(domain.ModelOption{}) {
			properties["id"].(map[string]any)["maxLength"] = 128
			properties["name"].(map[string]any)["maxLength"] = 256
			properties["reasoning_efforts"].(map[string]any)["maxItems"] = 16
			properties["reasoning_efforts"].(map[string]any)["uniqueItems"] = true
			properties["reasoning_efforts"].(map[string]any)["items"].(map[string]any)["maxLength"] = 64
		}
		if t == reflect.TypeOf(domain.Capability{}) {
			properties["models"].(map[string]any)["maxItems"] = 64
			properties["model_discovery"].(map[string]any)["enum"] = []string{"", "reported", "unavailable", "unsupported"}
		}
		if t == reflect.TypeOf(domain.TestSuite{}) {
			properties["stage"].(map[string]any)["enum"] = []string{"merge", "project", "release"}
			properties["id"].(map[string]any)["pattern"] = domain.ChatIdentifier.String()
			properties["checks"].(map[string]any)["minItems"] = 1
			properties["checks"].(map[string]any)["maxItems"] = 32
		}
		if t == reflect.TypeOf(domain.VerificationRequest{}) {
			properties["budget_seconds"].(map[string]any)["minimum"] = 1
			properties["budget_seconds"].(map[string]any)["maximum"] = domain.MaxTaskBudgetSeconds
			properties["max_run_seconds"].(map[string]any)["minimum"] = 1
			properties["max_run_seconds"].(map[string]any)["maximum"] = domain.MaxRunDurationSeconds
			properties["max_retries"].(map[string]any)["minimum"] = 0
			properties["max_retries"].(map[string]any)["maximum"] = 2
		}
		if t == reflect.TypeOf(domain.Task{}) || t == reflect.TypeOf(domain.TaskProposal{}) || t == reflect.TypeOf(domain.PlanningDocument{}) {
			properties["budget_seconds"].(map[string]any)["minimum"] = 1
			properties["budget_seconds"].(map[string]any)["maximum"] = domain.MaxTaskBudgetSeconds
		}
		if t == reflect.TypeOf(domain.Task{}) || t == reflect.TypeOf(domain.TaskProposal{}) {
			properties["max_run_seconds"].(map[string]any)["minimum"] = 1
			properties["max_run_seconds"].(map[string]any)["maximum"] = domain.MaxRunDurationSeconds
			properties["max_run_seconds"].(map[string]any)["description"] = "Finite single Run limit; must be <= budget_seconds."
		}
		if t == reflect.TypeOf(domain.Project{}) {
			properties["total_budget_seconds"].(map[string]any)["deprecated"] = true
			properties["total_budget_seconds"].(map[string]any)["description"] = "Ignored legacy field. Project used/reserved are cumulative statistics, never an allowance."
			filtered := []string{}
			for _, k := range required {
				if k != "total_budget_seconds" {
					filtered = append(filtered, k)
				}
			}
			required = filtered
		}
		if t == reflect.TypeOf(domain.ConsultationAccount{}) || t == reflect.TypeOf(domain.ChatOverview{}) {
			properties["budget_seconds"].(map[string]any)["deprecated"] = true
			properties["budget_seconds"].(map[string]any)["description"] = "Ignored legacy project allowance field; cumulative telemetry only."
		}
		defs[t.Name()] = map[string]any{"type": "object", "properties": properties, "required": required, "additionalProperties": false}
	}
	schema := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": "https://coordica.local/contracts/v1", "title": "Coordica v1", "$defs": defs}
	b, e := json.MarshalIndent(schema, "", "  ")
	must(e)
	must(os.MkdirAll("api", 0755))
	must(os.MkdirAll("web/src", 0755))
	must(os.WriteFile(filepath.Join("api", "v1.schema.json"), append(b, '\n'), 0644))
	must(os.WriteFile("web/src/api.generated.ts", []byte(ts.String()), 0644))
}

var timeType = reflect.TypeOf(time.Time{})

func tsType(t reflect.Type) string {
	if t == timeType {
		return "string"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return tsType(t.Elem()) + " | null"
	case reflect.Slice:
		return "(" + tsType(t.Elem()) + ")[] | null"
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			panic(t.String())
		}
		return "Record<string, " + tsType(t.Elem()) + ">"
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64:
		return "number"
	case reflect.Struct:
		return t.Name()
	}
	panic(t.String())
}
func schemaType(t reflect.Type) any {
	return schemaTypeMode(t, false)
}

func schemaTypeMode(t reflect.Type, nonNullArrays bool) any {
	if t == timeType {
		return map[string]any{"type": "string", "format": "date-time"}
	}
	switch t.Kind() {
	case reflect.Pointer:
		return map[string]any{"anyOf": []any{schemaType(t.Elem()), map[string]any{"type": "null"}}}
	case reflect.Slice:
		var kind any = []string{"array", "null"}
		if nonNullArrays {
			kind = "array"
		}
		return map[string]any{"type": kind, "items": schemaTypeMode(t.Elem(), nonNullArrays)}
	case reflect.Map:
		if t.Key().Kind() != reflect.String || nonNullArrays {
			panic(t.String())
		}
		return map[string]any{"type": "object", "additionalProperties": schemaTypeMode(t.Elem(), false)}
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int64:
		return map[string]any{"type": "integer"}
	case reflect.Struct:
		return map[string]any{"$ref": "#/$defs/" + t.Name()}
	}
	panic(t.String())
}

// The native final-output contract is a strict subset of the domain contracts.
// It has no transport records, nullable arrays, or independent proposal DTOs.
func leaderSchema() []byte {
	return strictNativeSchema("LeaderResult", domain.LeaderResult{}, domain.TaskProposal{}, domain.ScopeProposal{}, domain.MajorDecisionProposal{})
}

func requirementSchema() []byte {
	return strictNativeSchema("RequirementPlan", domain.RequirementPlan{}, domain.RequirementTaskUpdate{}, domain.RequirementNewTask{}, domain.TaskProposal{}, domain.MajorDecisionProposal{})
}

func strictNativeSchema(rootName string, types ...any) []byte {
	defs := map[string]any{}
	for _, value := range types {
		t := reflect.TypeOf(value)
		properties := map[string]any{}
		required := []string{}
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			name := strings.Split(f.Tag.Get("json"), ",")[0]
			properties[name] = schemaTypeMode(f.Type, true)
			required = append(required, name)
		}
		defs[t.Name()] = map[string]any{"type": "object", "properties": properties, "required": required, "additionalProperties": false}
	}
	root := defs[rootName].(map[string]any)
	// Keep an explicit object root for native structured-output providers.
	schema := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": defs}
	for key, value := range root {
		schema[key] = value
	}
	b, err := json.MarshalIndent(schema, "", "  ")
	must(err)
	return append(b, '\n')
}
func executionSchema() []byte {
	t := reflect.TypeOf(domain.ExecutionIntent{})
	properties := map[string]any{}
	required := []string{}
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		name := strings.Split(f.Tag.Get("json"), ",")[0]
		properties[name] = schemaTypeMode(f.Type, true)
		required = append(required, name)
	}
	properties["version"].(map[string]any)["enum"] = []int{domain.ExecutionIntentVersion}
	properties["status"].(map[string]any)["enum"] = []string{"completed", "scope_requested", "blocked"}
	schema := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": "https://coordica.local/contracts/execution/v1", "title": "Coordica execution intent v1", "type": "object", "properties": properties, "required": required, "additionalProperties": false}
	b, err := json.MarshalIndent(schema, "", "  ")
	must(err)
	return append(b, '\n')
}

func must(e error) {
	if e != nil {
		panic(e)
	}
}

func consultSchema() []byte {
	b, e := json.MarshalIndent(map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "type": "object", "properties": map[string]any{"reply": map[string]any{"type": "string", "minLength": 1, "maxLength": 16384}}, "required": []string{"reply"}, "additionalProperties": false}, "", "  ")
	must(e)
	return append(b, '\n')
}

