func TestValidationContractCommand(t *testing.T) {
	for i, arg := range os.Args {
		if arg != "--validation-contract" || len(os.Args) <= i+1 {
			continue
		}
		switch os.Args[i+1] {
		case "output":
			if err := os.MkdirAll("build", 0700); err != nil {
				os.Exit(9)
			}
			if err := os.WriteFile("build/output", []byte("generated by check"), 0600); err != nil {
				os.Exit(9)
			}
		case "mutate":
			if err := os.WriteFile("src/feature.txt", []byte("mutated by check"), 0600); err != nil {
				os.Exit(9)
			}
		case "flaky":
			if _, err := os.Stat(os.Args[i+2]); err != nil {
				if err := os.WriteFile(os.Args[i+2], []byte("first attempt failed"), 0600); err != nil {
					os.Exit(9)
				}
				fmt.Println("temporary external dependency unavailable")
				os.Exit(4)
			}
		}
		os.Exit(0)
	}
}

func validationContractFixture(t *testing.T, mode string, outputs []string, maxRetries int) *itFixture {
	t.Helper()
	f := newITFixture(t)
	binary, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	args := []string{"-test.run=^TestValidationContractCommand$", "--", "--validation-contract", mode}
	if mode == "flaky" {
		args = append(args, filepath.Join(t.TempDir(), "external-check-marker"))
	}
	if err := f.s.DB.Update(context.Background(), func(tx *store.Tx) error {
		p, err := getProject(tx)
		if err != nil {
			return err
		}
		p.Checks = []domain.Check{{Name: "builder", Command: binary, Args: args,
			RequiredPaths: []string{"src/feature.txt"}, OutputPaths: outputs, TimeoutSeconds: 10}}
		return tx.Put("project", p.ID, p)
	}); err != nil {
		t.Fatal(err)
	}
	seedCurrentPolicyBaseline(t, f.s)
	req := admitRecoveryGoal(t, f)
	raw, err := f.s.CreateTask(context.Background(), f.owner, ID("task_"), domain.Task{
		Title: "Implement module", Description: "Add feature", Acceptance: "Compile the feature", RequirementIDs: []string{req.ID},
		Tool: "codex", AllowedPaths: []string{"src/**"}, MaxRepairs: 2, MaxRetries: maxRetries,
	})
	task := itDecode[domain.Task](t, raw, err)
	if _, err := f.s.TaskAction(context.Background(), f.owner, ID("approve_"), task.ID, "approve",
		domain.VersionRequest{ExpectedVersion: task.Version}); err != nil {
		t.Fatal(err)
	}
	f.implement(t, "src/feature.txt")
	return f
}

func currentContractTask(t *testing.T, f *itFixture) domain.Task {
	t.Helper()
	id := f.candidate(t).TaskID
	for _, task := range f.snapshot(t).Tasks {
		if task.ID == id {
			return task
		}
	}
	t.Fatal("missing current task")
	return domain.Task{}
}

func TestDeclaredBuildOutputsPassChecksReviewAndRealGitIntegration(t *testing.T) {
	f := validationContractFixture(t, "output", []string{"build/**"}, 2)
	candidate := f.candidate(t)
	if candidate.State != "reviewing" || len(candidate.CheckPlan.OutputPaths) != 1 || candidate.CheckPlan.OutputPaths[0] != "build/**" {
		t.Fatal("per-check output declaration did not reach immutable merge plan", candidate)
	}
	f.reviewAndValidate(t)
	if err := f.w.Tick(context.Background()); err != nil {
		t.Fatal(err)
	}
	if f.candidate(t).State != "landed" || currentContractTask(t, f).State != "integrated" {
		t.Fatal("declared build outputs prevented integration")
	}
}

func TestUndeclaredCheckOutputsHoldExactCandidateWithoutCodeRepairs(t *testing.T) {
	f := validationContractFixture(t, "output", nil, 2)
	candidate := f.candidate(t)
	task := currentContractTask(t, f)
	if candidate.State != "rejected" || task.HoldReason != "check_configuration" || task.Repairs != 0 || task.Retries != 0 || task.CurrentCandidateID != candidate.ID {
		t.Fatal("configuration failure was sent to developer or lost fixed input", task, candidate)
	}
	for _, r := range f.snapshot(t).Runs {
		if r.Kind == "validation" && (r.FailureKind != "check_outputs" || !r.Quiescent || r.State != "failed") {
			t.Fatal("output-policy failure lost process evidence", r)
		}
	}
	before := f.snapshot(t)
	for range 2 {
		if err := f.w.Tick(context.Background()); err != nil {
			t.Fatal(err)
		}
	}
	after := f.snapshot(t)
	if len(after.Runs) != len(before.Runs) || len(failureCases(t, f.s)) != 0 || len(after.Decisions) != 1 || after.Decisions[0].Kind != "check_configuration" {
		t.Fatal("configuration hold spawned pointless repairs/diagnoses", after.Decisions)
	}
	main, err := f.g.Query(context.Background(), f.remote, "refs/heads/main")
	if err != nil || main != f.b {
		t.Fatal("failed candidate reached main", main, err)
	}
}

