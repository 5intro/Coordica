func TestTransientCheckRetryUsesSameCandidateAndPreservesCodeRepairAllowance(t *testing.T) {
	f := validationContractFixture(t, "flaky", nil, 2)
	candidate := f.candidate(t)
	task := currentContractTask(t, f)
	cases := failureCases(t, f.s)
	if task.HoldReason != "failure_assessment" || task.Repairs != 0 || len(cases) != 1 || cases[0].SourceCandidateID != candidate.ID {
		t.Fatal("real failed precheck skipped Leader diagnosis", task, cases)
	}
	sf := &serviceFixture{s: f.s, owner: f.owner, node: f.node}
	got := runRecovery(t, sf, domain.FailureRecoveryPlan{Category: "execution_failure", Reason: "Retry transient dependency check on unchanged code",
		Action: "retry_validation", Tasks: []domain.TaskProposal{}})
	if got.State != "applied" {
		t.Fatal("bounded check retry was not applied", got)
	}
	retry := f.candidate(t)
	task = currentContractTask(t, f)
	if retry.ID != candidate.ID || retry.Commit != candidate.Commit || retry.CheckPlan.Digest != candidate.CheckPlan.Digest ||
		task.Retries != 1 || task.Repairs != 0 || task.CurrentCandidateID != candidate.ID {
		t.Fatal("validation retry changed source, policy or code counters", retry, task)
	}
	var original domain.Run
	for _, run := range f.snapshot(t).Runs {
		if run.Kind == "validation" {
			original = run
		}
	}
	if err := f.w.finishValidation(context.Background(), original, candidate, nil, errors.New("late old failure"), true, false); err != nil {
		t.Fatal(err)
	}
	if f.candidate(t).State != "prechecking" || currentContractTask(t, f).Retries != 1 {
		t.Fatal("late old validation overwrote the replacement attempt")
	}
	if err := f.w.Tick(context.Background()); err != nil {
		t.Fatal(err)
	}
	if f.candidate(t).State != "reviewing" {
		t.Fatal("fresh command results did not reach independent review", f.candidate(t))
	}
	f.reviewAndValidate(t)
	if err := f.w.Tick(context.Background()); err != nil {
		t.Fatal(err)
	}
	if f.candidate(t).State != "landed" {
		t.Fatal("same fixed candidate failed to land after fresh checks/review")
	}
	implementations := 0
	for _, run := range f.snapshot(t).Runs {
		if run.Kind == "implement" {
			implementations++
		}
	}
	if implementations != 1 {
		t.Fatal("check-only retry launched a developer", implementations)
	}
	for _, run := range f.snapshot(t).Runs {
		if run.ID == original.ID && (len(run.CheckResults) != 1 || run.CheckResults[0].Passed ||
			!strings.Contains(run.CheckResults[0].Output, "temporary external dependency")) {
			t.Fatal("fresh checks overwrote the original failed command evidence", run)
		}
	}
}

func TestValidationRetryCannotResetExhaustedPlatformCounter(t *testing.T) {
	f := validationContractFixture(t, "flaky", nil, 0)
	sf := &serviceFixture{s: f.s, owner: f.owner, node: f.node}
	got := runRecovery(t, sf, domain.FailureRecoveryPlan{Category: "execution_failure", Reason: "No retries left",
		Action: "retry_validation", Tasks: []domain.TaskProposal{}})
	task := currentContractTask(t, f)
	if got.State == "applied" || task.Retries != 0 || task.Repairs != 0 || f.candidate(t).State != "rejected" {
		t.Fatal("exhausted retries were refreshed", got, task)
	}
}
